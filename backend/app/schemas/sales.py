from datetime import datetime
from decimal import Decimal
from typing import List, Optional

from pydantic import BaseModel, Field


class SalesOrderItemCreate(BaseModel):
    product_id: int
    quantity: Decimal = Field(..., gt=0)
    unit_price: Decimal = Field(..., ge=0)


class SalesOrderItemResponse(BaseModel):
    id: int
    sales_order_id: int
    product_id: int
    product_name: Optional[str] = None
    product_sku: Optional[str] = None
    quantity: Decimal
    unit_price: Decimal
    subtotal: Decimal

    model_config = {"from_attributes": True}


class SalesOrderCreate(BaseModel):
    customer_id: Optional[int] = None
    warehouse_id: Optional[int] = None
    order_number: Optional[str] = None  # Autogenerated if empty: SO-YYYYMMDD-XXXX
    notes: Optional[str] = None
    items: List[SalesOrderItemCreate] = Field(..., min_length=1)


class SalesOrderResponse(BaseModel):
    id: int
    organization_id: int
    customer_id: Optional[int] = None
    customer_name: Optional[str] = None
    warehouse_id: Optional[int] = None
    warehouse_name: Optional[str] = None
    created_by: Optional[int] = None
    order_number: str
    status: str
    total_amount: Decimal
    notes: Optional[str] = None
    created_at: datetime
    confirmed_at: Optional[datetime] = None
    items: List[SalesOrderItemResponse] = []

    model_config = {"from_attributes": True}


class SalesConfirmRequest(BaseModel):
    warehouse_id: Optional[int] = None  # Optional override; default: warehouse SO atau gudang aktif pertama
    notes: Optional[str] = None
